#!/usr/bin/env python3
"""PIM baseline on the SynCron machine (HBM3E): the CPU-baseline campaign's BFS / PR / SSSP / SpMV, unmodified
OpenMP code (gbbs fork, built by DAMOV/workloads/gbbs_zsim/build.sh), on SynCron's 4 units x 16 in-order cores.

Scope: plans/PIM-BASELINE-SYNCRON-HBM3E-SCOPE.md. Machine = syncron/run.py's HBM3E machine (same cores, caches,
crossbar, SEs, inter-unit links) with these differences only:
  - memory addressing channel_interleave (HBM3E-24Gb_12hi-4unit-ci.yaml): no per-unit placement (decision D2);
  - phaseLength 1000 (100 was needed only for the polled barrier timing).

  ./run.py gen                 write configs/<cell>.cfg for every cell
  ./run.py run <cell> [...]    run cells (docker, zsim-bionic-r2); logs in zsim_stats/pimbase/logs/
  ./run.py variant <cell> <tag> <ENV=VAL ...>   one-off variant: stats/logs named <cell>__<tag>, extra env
  ./run.py list
"""
import os
import subprocess
import sys
from pathlib import Path

SIM = Path(__file__).resolve().parents[1]           # DAMOV/simulator
ROOT = SIM.parents[1]                                # pnm-repos (mounted at /pnm)
DATA = Path("/media/data/andronicus/datasets/aws_datasets")   # mounted at /data
IMAGE = "zsim-bionic-r2"
BIN = "/pnm/DAMOV/workloads/gbbs_zsim/bin"

# Same command lines as gbbs/scripts/cpu_baseline/docker/run_cell.sh, with -rounds 1 (one ROI).
CELLS = {
    "bfs.s16":            f"{BIN}/BFS -s -b -push -src 0 -rounds 1 /data/gbbs/s16.bin",
    "bfs.youtube":        f"{BIN}/BFS -s -b -push -src 0 -rounds 1 /data/gbbs/youtube_bfs.bin",
    "pr.s16":             f"{BIN}/PageRank -s -b -push -iters 1 -rounds 1 /data/gbbs/s16.bin",
    "pr.youtube":         f"{BIN}/PageRank -s -b -push -iters 1 -rounds 1 /data/gbbs/youtube.bin",
    "sssp.s16":           f"{BIN}/BellmanFord -s -w -b -pull -src 0 -rounds 1 /data/gbbs/s16.wbin",
    "sssp.youtube-0fix":  f"{BIN}/BellmanFord -s -w -b -pull -src 0 -rounds 1 /data/gbbs/youtube_sssp.wbin",
    "spmv.ML_Geer":       f"{BIN}/spmv /data/spmv/ML_Geer_csr.mtx_padded.bin -rounds 1",
    "spmv.HV15R":         f"{BIN}/spmv /data/spmv/HV15R_csr.mtx_padded.bin -rounds 1",
}
# Validation of the atomics model (P1): DAMOV/workloads/gbbs_zsim/atomic_ubench.cpp
UBENCH = {
    "ubench.local1":    f"{BIN}/atomic_ubench 0 1 1000",            # core 0 (unit 0), home unit 0
    "ubench.remote1":   f"{BIN}/atomic_ubench 1 1 1000",            # core 0, home unit 1
    "ubench.private64": f"{BIN}/atomic_ubench 0 64 1000",           # 64 threads, own lines, all homed in unit 0
    "ubench.shared64":  f"{BIN}/atomic_ubench 0 64 200 shared",     # 64 threads on one line
}
CELLS.update(UBENCH)
THREADS = 64
# As the CPU campaign (run_cell.sh), except OMP_PROC_BIND / OMP_PLACES: under zsim the simulator places threads
# on cores (one per core), so libomp must not try to bind to host CPUs.
ENV = f"OMP_NUM_THREADS={THREADS} OMP_WAIT_POLICY=active"

UNITS, CORES_PER_UNIT = 4, 16


def config(cell: str, cmd: str, extra_sys: str = "") -> str:
    cores = "\n".join(
        f"""        unit{u} = {{ type = "Timing"; cores = {CORES_PER_UNIT}; icache = "l1i_u{u}"; dcache = "l1d_u{u}"; pim = true; }};"""
        for u in range(UNITS))
    caches = "\n".join(
        f"""        l1i_u{u} = {{ caches = {CORES_PER_UNIT}; size = 16384; latency = 4; array = {{ type = "SetAssoc"; ways = 2; }}; }};
        l1d_u{u} = {{ caches = {CORES_PER_UNIT}; size = 16384; latency = 4; array = {{ type = "SetAssoc"; ways = 2; }}; }};"""
        for u in range(UNITS))
    children = " ".join(f"l1i_u{u}|l1d_u{u}" for u in range(UNITS))
    return f"""// Generated by pimbase/run.py -- PIM baseline cell {cell} on the SynCron machine, HBM3E, interleaved.
sys = {{
    lineSize = 64;
    frequency = 2000;           // our SynCron model (paper Table 5: 2500); = UpDown lane clock
    networkType = "mesh";
    networkFile = "syncron/network_4x16.mesh";

    cores = {{
{cores}
    }};

    caches = {{
{caches}
        // No shared cache, no coherence in an NDP unit (SynCron Table 5); bypassed LLC as in syncron/run.py.
        llc = {{
            caches = 1; banks = {UNITS}; size = 4194304; latency = 0;
            array = {{ type = "SetAssoc"; hash = "H3"; ways = 16; }};
            bypass = true;
            children = "{children}";
        }};
    }};

    syncron = {{
        scheme = "syncron";
        units = {UNITS};
        coresPerUnit = {CORES_PER_UNIT};
        stEntries = 64;
        indexingCounters = 256;
        spuMHz = 1000;
        serviceCycles = 12;
        localMsgCycles = 2;
        globalMsgCycles = 80;
        linkBwGbps = 12.80;
        msgBytes = 18;
        meshX = 0;
        bytesPerUnit = 38654705664L;
        // Memory is channel_interleave (D2), so a line's home unit = (addr / 32 KiB) % 4: HBM3E 64 B transactions x
        // 32 column positions = 2 KiB per channel, 16 channels per stack. The Master SE of an atomic's lock is there.
        homeInterleaveBytes = 32768;
        // D3: every atomic RMW instruction (app, OpenMP runtime, libc) goes through a SynCron lock on its line.
        routeAtomics = true;
        // Many cores load one SE at once here, so SPUs and links serve messages in simulated-arrival order (a
        // calendar per server) instead of zsim's bound-phase call order, which wasted ~70% of SE0's time in the
        // 64-thread validation (spuInversions). Off in every earlier SynCron run.
        gapFill = true;
        overflowMemCycles = 83;     // HBM3E measured loaded access latency (41.6 ns), as syncron/run.py
        traceFrom = 0;
        traceCount = 0;
{extra_sys}    }};

    mem = {{
        type = "Ramulator2";
        clockMode = "ns";
        ramulatorConfig = "ramulator2-configs/HBM3E-24Gb_12hi-4unit-ci.yaml";
        latency = 1;
    }};
}};

sim = {{
    pimMode = false;
    stats = "zsim_stats/pimbase/{cell}";
    phaseLength = 1000;
    statsPhaseInterval = 100000000;
    printHierarchy = true;
    gmMBytes = 8192;
    pinOptions = "-ifeellucky";
    deadlockDetection = false;
}};

process0 = {{
    command = "{cmd}";
    startFastForwarded = True;
}};
"""


def gen():
    d = SIM / "pimbase" / "configs"
    d.mkdir(parents=True, exist_ok=True)
    for cell, cmd in CELLS.items():
        (d / f"{cell}.cfg").write_text(config(cell, cmd))
    print(f"{len(CELLS)} configs in {d}")


def run(cell: str, env: str = ENV):
    logs = SIM / "zsim_stats" / "pimbase" / "logs"
    logs.mkdir(parents=True, exist_ok=True)
    script = (f"cd /pnm/DAMOV/simulator && export {env} && "
              f"{{ time setarch x86_64 -R ./build/opt/zsim pimbase/configs/{cell}.cfg "
              f"> zsim_stats/pimbase/logs/{cell}.log 2>&1 ; }} 2> zsim_stats/pimbase/logs/{cell}.time; rc=$?; "
              f"chown -R {os.getuid()}:{os.getgid()} zsim_stats/pimbase; exit $rc")
    cmd = ["docker", "run", "--rm", "--privileged", "--name", f"pimbase_{cell.replace('.', '_')}",
           "-v", f"{ROOT}:/pnm", "-v", f"{DATA}:/data:ro", IMAGE, "bash", "-c", script]
    rc = subprocess.call(cmd)
    print(f"{cell}: rc={rc}")
    return rc


if __name__ == "__main__":
    if len(sys.argv) < 2 or sys.argv[1] not in ("gen", "run", "list", "variant"):
        print(__doc__)
        sys.exit(1)
    if sys.argv[1] == "gen":
        gen()
    elif sys.argv[1] == "variant":
        cell, tag, extra = sys.argv[2], sys.argv[3], sys.argv[4:]
        name = f"{cell}__{tag}"
        (SIM / "pimbase" / "configs" / f"{name}.cfg").write_text(config(name, CELLS[cell]))
        sys.exit(run(name, ENV + " " + " ".join(extra)))
    elif sys.argv[1] == "list":
        print("\n".join(CELLS))
    else:
        sys.exit(max(run(c) for c in sys.argv[2:]))
